-- @trace spec:proxy-container, order:2041-i3nk
-- @env TILLANDSIAS_PROXY_TIERS_DIR
-- @env TILLANDSIAS_PROXY_ALLOWLIST
-- @env TILLANDSIAS_PROXY_TIER_PORTS
--
-- build-proxy-allowlist.lua — images/proxy/allowlist.txt is generated from
-- the per-tier files in images/proxy/tiers/.
--
-- The tier files are the source of truth (curated-egress-tiers, step 1).
-- Until every container is served by its own tier port, the proxy's strict
-- port keeps serving the UNION of the tiers, and that union is this file.
-- A domain listed in two tiers (fonts are in both assets and registries)
-- appears once in the union: squid 6.x refuses a repeated or covered entry
-- as a FATAL config error, so this script also refuses a tier set whose
-- union would carry one.
--
-- PART 2: images/proxy/tier-ports.conf is generated here too. Each tier gets
-- its own Squid port, named tier_<tier> and matched with myportname. A client
-- on a tier port is held to that tier by NAME, at both ends of a CONNECT:
--   - http_access: the CONNECT target (dstdomain) must be in the tier;
--   - ssl_bump, after the step-1 peek: the client's SNI
--     (ssl::server_name --client-requested) must be in the tier, or the
--     connection is terminated. With NO SNI, squid's --client-requested
--     name falls back to the CONNECT target (measured live), so a no-SNI
--     client is judged by its target alone, still held to the tier.
-- So an allowed target with an off-tier SNI is refused, and so is the
-- reverse. Checking that the SNI RESOLVES to the CONNECT address is not done
-- here; that is 2041-8azp. Port 3128 keeps serving the union; 3129 is the
-- unrouted build port.
-- The port of a tier is FIXED below (append-only): a tier added later takes
-- the next free port, so no existing client's port ever moves.
--
--   (no args)  write the allowlist from the tiers
--   --check    regenerate in memory and compare with the committed file
--
-- Verdict grammar, one line on stdout (detail on stderr):
--   ok:proxy-allowlist:<n> domains,<t> tiers                 exit 0
--   violation:proxy-allowlist:stale                          exit 1
--   violation:proxy-allowlist:covered:<entry><<by>           exit 1
--   violation:proxy-allowlist:tier-covered:<tier>:<entry><<by> exit 1
--   blocked:proxy-allowlist:<file>-unreadable                exit 2

local DIR = env.get("TILLANDSIAS_PROXY_TIERS_DIR") or "images/proxy/tiers"
local OUT = env.get("TILLANDSIAS_PROXY_ALLOWLIST") or "images/proxy/allowlist.txt"
local PORTS_OUT = env.get("TILLANDSIAS_PROXY_TIER_PORTS") or "images/proxy/tier-ports.conf"
local TIERS = { "registries", "assets", "vcs", "providers", "model-hubs", "research" }
-- Fixed, append-only: never renumber an existing tier.
local TIER_PORT = { registries = 3130, assets = 3131, vcs = 3132, providers = 3133,
                    ["model-hubs"] = 3134, research = 3135 }

local PORTS_HEADER = [[
# @trace spec:proxy-container, order:2041-i3nk
# GENERATED by scripts/lua/build-proxy-allowlist.lua from images/proxy/tiers/.
# Do not edit: change the tier file, then run the script (litmus pins it).
#
# One Squid port per egress tier. squid.conf includes this file right after
# `ssl_bump peek ssl_bump_step1` and before every other http_access and
# ssl_bump rule, because Squid applies rules in order.
# A client on a tier port is held to its tier by NAME:
#   http_access  the CONNECT target must be in the tier;
#   ssl_bump     the client's SNI must be in the tier, else terminated
#                (no SNI: squid falls back to the CONNECT target).
# A refusal is a TCP reset, as on 3128 (deny_info TCP_RESET).
# SNI-to-address matching is 2041-8azp, not this file.
]]

local function tier_ports_conf()
    local out = { PORTS_HEADER }
    for _, tier in ipairs(TIERS) do
        local port = TIER_PORT[tier]
        if not port then
            verdict.emit("violation:proxy-allowlist:no-port-for-tier:" .. tier, 1)
        end
        local id = tier:gsub("%-", "_")
        local file = "/etc/squid/tiers/" .. tier .. ".txt"
        out[#out + 1] = table.concat({
            "",
            "# ----- tier " .. tier .. " : port " .. port .. " -----",
            "http_port " .. port .. " ssl-bump name=tier_" .. id .. " \\",
            "    tls-cert=/etc/squid/certs/intermediate.crt \\",
            "    tls-key=/etc/squid/certs/intermediate.key \\",
            "    generate-host-certificates=on \\",
            "    dynamic_cert_mem_cache_size=16MB",
            "acl on_tier_" .. id .. " myportname tier_" .. id,
            "acl dst_tier_" .. id .. ' dstdomain "' .. file .. '"',
            "acl sni_tier_" .. id .. ' ssl::server_name --client-requested "' .. file .. '"',
            "http_access allow CONNECT SSL_ports on_tier_" .. id .. " dst_tier_" .. id,
            "http_access allow !CONNECT on_tier_" .. id .. " dst_tier_" .. id,
            "http_access deny on_tier_" .. id,
            -- A refusal is a reset, as on 3128: without it squid bumps the
            -- denied CONNECT to serve an error page under the proxy's own CA,
            -- which a client sees as a completed handshake (measured live).
            "deny_info TCP_RESET on_tier_" .. id,
            "ssl_bump terminate on_tier_" .. id .. " !sni_tier_" .. id,
            "",
        }, "\n")
    end
    return table.concat(out)
end
local TIER_HEADER_LINES = 4

local HEADER = [[
# @trace spec:proxy-container
# GENERATED by scripts/lua/build-proxy-allowlist.lua from images/proxy/tiers/.
# Do not edit: change the tier file, then run the script (litmus pins it).
# Domain allowlist for Tillandsias proxy: the union of every tier.
# Format: .domain.com matches domain and all subdomains.
# One domain per line. Lines starting with # are comments.
#
# IMPORTANT: Do NOT list subdomains of already-listed domains.
# Squid 6.x treats subdomain duplicates as FATAL errors.
# Example: .googleapis.com already covers .storage.googleapis.com
]]

local function is_entry(line)
    return line ~= "" and line:sub(1, 1) ~= "#"
end

-- `.a.com` covers `a.com` and every `x.a.com`; a bare name covers itself.
local function covers(by, entry)
    if by == entry then return true end
    local apex = by:sub(1, 1) == "." and by:sub(2) or nil
    if not apex then return false end
    local e = entry:sub(1, 1) == "." and entry:sub(2) or entry
    return e == apex or e:sub(-#by) == by
end

local function main()
    local out = { HEADER }
    local seen = {}
    local listed = {}
    for _, tier in ipairs(TIERS) do
        local path = DIR .. "/" .. tier .. ".txt"
        local text = fs.read(path)
        if not text then
            verdict.emit("blocked:proxy-allowlist:" .. path .. "-unreadable", 2)
        end
        out[#out + 1] = "# ===== tier: " .. tier .. " (images/proxy/tiers/" .. tier .. ".txt) =====\n"
        local n = 0
        -- Each tier is also loaded as its own dstdomain and ssl::server_name
        -- list on its port, and squid refuses a covered entry there too.
        local in_tier = {}
        for line in (text .. "\n"):gmatch("(.-)\n") do
            n = n + 1
            if n > TIER_HEADER_LINES then
                if is_entry(line) then
                    for _, by in ipairs(in_tier) do
                        if covers(by, line) or covers(line, by) then
                            verdict.emit("violation:proxy-allowlist:tier-covered:" .. tier .. ":" .. line .. "<" .. by, 1)
                        end
                    end
                    in_tier[#in_tier + 1] = line
                    if not seen[line] then
                        for _, by in ipairs(listed) do
                            if covers(by, line) or covers(line, by) then
                                verdict.emit("violation:proxy-allowlist:covered:" .. line .. "<" .. by, 1)
                            end
                        end
                        seen[line] = true
                        listed[#listed + 1] = line
                        out[#out + 1] = line .. "\n"
                    end
                else
                    out[#out + 1] = line .. "\n"
                end
            end
        end
    end
    local body = table.concat(out):gsub("\n\n\n+", "\n\n")
    local ports = tier_ports_conf()
    local line = "ok:proxy-allowlist:" .. #listed .. " domains," .. #TIERS .. " tiers," .. #TIERS .. " tier ports"
    if arg and arg[1] == "--check" then
        for _, pair in ipairs({ { OUT, body }, { PORTS_OUT, ports } }) do
            local cur = fs.read(pair[1])
            if not cur then
                verdict.emit("blocked:proxy-allowlist:" .. pair[1] .. "-unreadable", 2)
            end
            if cur ~= pair[2] then
                io.stderr:write(pair[1] .. " differs from the tiers; run scripts/lua/build-proxy-allowlist.lua\n")
                verdict.emit("violation:proxy-allowlist:stale", 1)
            end
        end
    else
        fs.write(OUT, body)
        fs.write(PORTS_OUT, ports)
    end
    verdict.emit(line, 0)
end

main()
