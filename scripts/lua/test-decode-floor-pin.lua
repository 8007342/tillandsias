-- @env PATH SystemRoot TEMP TMP USERPROFILE LOCALAPPDATA HOME
--
-- test-decode-floor-pin.lua — images/inference/decode-floor-pin.sh, RUN against a
-- stub `ollama` that keeps a model store on disk (the PATH seam the script
-- documents). The real script is sourced unchanged; only `ollama` is faked.
--
-- The store: one directory per model (':' encoded as '__' so the fixture runs
-- on Windows too) holding `size` (what `ollama show` prints as parameters) and
-- `mf` (the Modelfile: a FROM line plus PARAMETER lines). `ollama create NAME -f
-- F` behaves as ollama does for the two shapes the script writes: a FROM that
-- names NAME itself inherits NAME's parameters and adds F's; a FROM of anything
-- else (a blob path) replaces the Modelfile with F.
--
-- Models: small (0.5B), embed (137M, carries num_ctx 8192), big (7.6B), mine
-- (0.5B with the operator's own num_gpu 99), odd (no readable size).
--
-- Arms:
--   1 opted in, floor 3: small and embed pinned num_gpu 0 and recorded; big,
--     mine and odd untouched; grammar line exact
--   2 opted in again: kept=2, no duplicate record, no second num_gpu line
--   3 OPT-IN OFF (the coordinator's arm): every recorded pin restored, NO
--     residual num_gpu 0 anywhere, the record removed, embed keeps num_ctx 8192,
--     mine keeps its num_gpu 99
--   4 a floor that drops below a pinned model restores it (floor 0.1, measured)
--   5 floor `all` (the CPU won throughout) pins big too
--   6 a missing or junk floor falls back to 3, labelled default-provisional
--
-- Usage: tillandsias-plan script run scripts/lua/test-decode-floor-pin.lua

local SUBJECT = "images/inference/decode-floor-pin.sh"
if not fs.exists(SUBJECT) then
    verdict.could_not_run("decode-floor-pin-fixture", "subject missing: " .. SUBJECT)
end

local function run(argv, extra_env)
    local env_tbl = {}
    for _, k in ipairs({ "PATH", "SystemRoot", "TEMP", "TMP", "USERPROFILE", "LOCALAPPDATA", "HOME" }) do
        local v = env.get(k)
        if v ~= nil then env_tbl[k] = v end
    end
    for k, v in pairs(extra_env or {}) do env_tbl[k] = v end
    return proc.run({ argv = argv, timeout_ms = 120000, env = env_tbl })
end

local ROOT = text.trim(run({ "git", "rev-parse", "--show-toplevel" }).stdout or "")
local REL = "target/plan-scratch/decode-floor-pin-" .. time.iso_utc():gsub("[^%w]", "") .. "-" .. tostring(math.random(100000, 999999))
local ABS = ROOT .. "/" .. REL
fs.mkdir(REL .. "/bin")

local STUB = [=[#!/usr/bin/env bash
S="$TDF_STORE"
enc() { printf '%s' "$1" | sed 's/:/__/g'; }
dec() { printf '%s' "$1" | sed 's/__/:/g'; }
case "$1" in
  list)
    echo "NAME    ID    SIZE    MODIFIED"
    for d in "$S"/*/; do [ -d "$d" ] && echo "$(dec "$(basename "$d")")    0000    1 MB    now"; done ;;
  show)
    if [ "$2" = "--parameters" ]; then
      grep '^PARAMETER ' "$S/$(enc "$3")/mf" | sed 's/^PARAMETER //'
    elif [ "$2" = "--modelfile" ]; then
      echo "# Modelfile generated by \"ollama show\""
      cat "$S/$(enc "$3")/mf"
    else
      [ -d "$S/$(enc "$2")" ] || exit 1
      echo "  Model"
      [ -s "$S/$(enc "$2")/size" ] && echo "    parameters          $(cat "$S/$(enc "$2")/size")    "
      true
    fi ;;
  create)
    name="$2"; f="$4"; d="$S/$(enc "$name")"
    from="$(sed -n 's/^FROM //p' "$f" | head -1)"
    if [ "$from" = "$name" ]; then
      { cat "$d/mf"; grep '^PARAMETER ' "$f"; } > "$d/mf.new"
    else
      grep -v '^#' "$f" > "$d/mf.new"
    fi
    mv "$d/mf.new" "$d/mf" ;;
  *) exit 2 ;;
esac
]=]
fs.write(REL .. "/bin/ollama", STUB)
run({ "chmod", "+x", ABS .. "/bin/ollama" })

local function seed(store)
    run({ "rm", "-rf", ABS .. "/" .. store })
    local models = {
        { "qwen2.5__0.5b", "494.03M", "FROM /blobs/sha256-small\nTEMPLATE x\n" },
        { "nomic-embed-text__latest", "137M", "FROM /blobs/sha256-embed\nPARAMETER num_ctx 8192\n" },
        { "qwen2.5__7b", "7.6B", "FROM /blobs/sha256-big\n" },
        { "mine__latest", "494.03M", "FROM /blobs/sha256-mine\nPARAMETER num_gpu 99\n" },
        { "odd__latest", "", "FROM /blobs/sha256-odd\n" },
    }
    for _, m in ipairs(models) do
        fs.mkdir(REL .. "/" .. store .. "/" .. m[1])
        fs.write(REL .. "/" .. store .. "/" .. m[1] .. "/size", m[2])
        fs.write(REL .. "/" .. store .. "/" .. m[1] .. "/mf", m[3])
    end
end

local DRIVER = REL .. "/driver.sh"
fs.write(DRIVER, ". \"$TDF_SUBJECT\"\ntillandsias_decode_floor_reconcile \"$TDF_STATE\"\n")

local function reconcile(store, tier, floor, source)
    local e = {
        PATH = ABS .. "/bin:" .. (env.get("PATH") or ""),
        TDF_STORE = ABS .. "/" .. store,
        TDF_SUBJECT = ROOT .. "/" .. SUBJECT,
        TDF_STATE = ABS .. "/" .. store .. ".pins",
        TILLANDSIAS_INFERENCE_TIER = tier,
    }
    if floor ~= nil then e.TILLANDSIAS_DECODE_FLOOR_B = floor end
    if source ~= nil then e.TILLANDSIAS_DECODE_FLOOR_SOURCE = source end
    local r = run({ "bash", ABS .. "/driver.sh" }, e)
    return text.trim(r.stdout or ""), (r.stderr or "")
end

local function mf(store, m) return fs.read(REL .. "/" .. store .. "/" .. m .. "/mf") end
local function state(store)
    if not fs.exists(REL .. "/" .. store .. ".pins") then return nil end
    return fs.read(REL .. "/" .. store .. ".pins")
end
local function count(hay, needle)
    local n, i = 0, 1
    while true do
        local j = string.find(hay, needle, i, true)
        if not j then return n end
        n, i = n + 1, j + 1
    end
end

local passed, failed = 0, 0
local function check(name, cond, why)
    if cond then passed = passed + 1; out.line("ok:   " .. name)
    else failed = failed + 1; out.line("FAIL: " .. name .. " — " .. why) end
end

-- 1 opted in, floor 3.
seed("s")
local line, err = reconcile("s", "gpu-vulkan", "3", "provisional")
check("1 grammar line",
    line == "decode-floor: tier=gpu-vulkan floor_b=3 source=provisional pinned=2 kept=0 restored=0 skipped=2",
    "[" .. line .. "] stderr=[" .. err .. "]")
check("1 small and embed pinned",
    count(mf("s", "qwen2.5__0.5b"), "PARAMETER num_gpu 0") == 1
        and count(mf("s", "nomic-embed-text__latest"), "PARAMETER num_gpu 0") == 1,
    "small=[" .. mf("s", "qwen2.5__0.5b") .. "] embed=[" .. mf("s", "nomic-embed-text__latest") .. "]")
check("1 big, mine and odd untouched",
    mf("s", "qwen2.5__7b") == "FROM /blobs/sha256-big\n"
        and mf("s", "mine__latest") == "FROM /blobs/sha256-mine\nPARAMETER num_gpu 99\n"
        and mf("s", "odd__latest") == "FROM /blobs/sha256-odd\n",
    "big=[" .. mf("s", "qwen2.5__7b") .. "] mine=[" .. mf("s", "mine__latest") .. "]")
local st = state("s") or ""
check("1 exactly the two pins recorded",
    count(st, "\n") == 2 and text.contains(st, "qwen2.5:0.5b\n") and text.contains(st, "nomic-embed-text:latest\n")
        and not text.contains(st, "mine"),
    "state=[" .. st .. "]")

-- 2 again.
line = reconcile("s", "gpu-vulkan", "3", "provisional")
check("2 idempotent", text.contains(line, "pinned=0 kept=2 restored=0")
    and count(mf("s", "qwen2.5__0.5b"), "num_gpu") == 1 and count(state("s") or "", "\n") == 2,
    "[" .. line .. "]")

-- 3 OPT-IN OFF: no residue.
line = reconcile("s", "cpu", nil, nil)
local residue = 0
for _, m in ipairs({ "qwen2.5__0.5b", "nomic-embed-text__latest", "qwen2.5__7b", "odd__latest" }) do
    residue = residue + count(mf("s", m), "num_gpu 0")
end
check("3 opt-out restores both and reports it",
    line == "decode-floor: tier=cpu floor_b=- source=- pinned=0 kept=0 restored=2 skipped=0", "[" .. line .. "]")
check("3 NO residual num_gpu 0 after opt-out", residue == 0, "residue=" .. residue)
check("3 the record is removed", state("s") == nil, "state=[" .. tostring(state("s")) .. "]")
check("3 embed keeps num_ctx, mine keeps num_gpu 99",
    text.contains(mf("s", "nomic-embed-text__latest"), "PARAMETER num_ctx 8192")
        and mf("s", "mine__latest") == "FROM /blobs/sha256-mine\nPARAMETER num_gpu 99\n",
    "embed=[" .. mf("s", "nomic-embed-text__latest") .. "]")

-- 4 a floor that drops below the pinned models restores them.
seed("t")
reconcile("t", "gpu-vulkan", "3", "provisional")
line = reconcile("t", "gpu-vulkan", "0.1", "measured")
check("4 a lower measured floor gives the GPU back",
    text.contains(line, "floor_b=0.1 source=measured pinned=0 kept=0 restored=2")
        and count(mf("t", "qwen2.5__0.5b"), "num_gpu") == 0 and state("t") == nil,
    "[" .. line .. "] state=[" .. tostring(state("t")) .. "]")

-- 5 floor all.
seed("u")
line = reconcile("u", "gpu-vulkan", "all", "cpu-wins")
check("5 floor all pins big too",
    text.contains(line, "floor_b=all source=cpu-wins pinned=3")
        and count(mf("u", "qwen2.5__7b"), "PARAMETER num_gpu 0") == 1,
    "[" .. line .. "]")

-- 6 junk floor.
seed("v")
line = reconcile("v", "gpu-vulkan", "3; rm -rf /", nil)
check("6 a junk floor falls back to the labelled provisional 3",
    text.contains(line, "floor_b=3 source=default-provisional pinned=2"), "[" .. line .. "]")

run({ "rm", "-rf", ABS })
if failed > 0 then
    verdict.emit("refused:decode-floor-pin-fixture:" .. failed .. "-of-" .. (passed + failed), 1)
end
verdict.emit("ok:decode-floor-pin-fixture:" .. passed .. " arms", 0)
