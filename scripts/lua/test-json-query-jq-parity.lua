-- @env PATH TMPDIR
-- @trace order:1375-rn9b, order:2073-i4jr, order:2079-sgp4, order:2380-wjrd
--
-- test-json-query-jq-parity.lua — `tillandsias-plan json get` prints what jq prints, byte for byte, with its
-- exit status, on every filter of scripts/portability/jq-subset-corpus.txt. The expectation is a GOLDEN made
-- from jq, so a host without jq checks it too; where jq is present a disagreement is printed as `drift:`,
-- advisory. The binary under test is a private snapshot: the resolved path is a build output another guard
-- may relink mid-run (2073-i4jr). A divergence prints its want, got and stderr.
-- Ported from the .sh of the same name.
--
-- Usage: tillandsias-plan script run scripts/lua/test-json-query-jq-parity.lua [-- --regenerate]
--   --regenerate rewrites the golden from host jq.
-- Verdict: ok:json-get-parity:<n> arms | violation:...:<n>-failed | refused:json-get-parity:<why>

local fixture = require "common.fixture"
local T = fixture.new("json-get-parity")
local SH = fixture.posix_shell()
local CORPUS, GOLDEN = "scripts/portability/jq-subset-corpus.txt", "scripts/portability/jq-subset-golden.txt"
local JQ = fixture.which("jq")

local cases = {}
for l in fs.read(CORPUS):gsub("\r\n", "\n"):gmatch("[^\n]+") do
    if l:sub(1, 1) ~= "#" and l:find("%S") then
        local flags, filter, input = l:match("^([^\t]*)\t([^\t]*)\t(.*)$")
        if not flags then T:refuse("corpus-line", l) end
        local argv = {}
        if flags ~= "_" then for a in flags:gmatch("%S+") do argv[#argv + 1] = a end end
        argv[#argv + 1] = filter
        cases[#cases + 1] = { argv = argv, filter = filter, input = input }
    end
end

-- A case under a tool (its argv prefix): its stdout, then "rc=<n>".
local function answer(tool, c)
    local argv = {}
    for _, a in ipairs(tool) do argv[#argv + 1] = a end
    for _, a in ipairs(c.argv) do argv[#argv + 1] = a end
    local r = proc.run{ argv = argv, stdin = c.input, timeout_ms = 30000, env = { PATH = env.get("PATH") } }
    return (r.stdout or "") .. "rc=" .. tostring(r.code), r.stderr or ""
end

if (arg or {})[1] == "--regenerate" then
    if not JQ then T:refuse("regenerate-needs-jq") end
    local lines = { "# jq-subset-golden.txt — generated by test-json-query-jq-parity.lua -- --regenerate",
        "# from " .. text.trim(T:must{ JQ, "--version" }.stdout) .. '. One block per corpus case: "@@case <n>", its stdout, "rc=<n>".' }
    for i, c in ipairs(cases) do
        lines[#lines + 1] = "@@case " .. i
        lines[#lines + 1] = answer({ JQ }, c)
    end
    local s = table.concat(lines, "\n") .. "\n"
    if text.contains(s, "\r") then T:refuse("regenerate-jq-writes-crlf", "regenerate where jq writes LF") end
    fs.write(GOLDEN, s)
    verdict.emit("ok:json-get-parity:regenerated:" .. #cases, 0)
end

local golden, n = {}, nil
for l in fs.read(GOLDEN):gsub("\r\n", "\n"):gmatch("([^\n]*)\n") do
    local at = l:match("^@@case (%d+)$")
    if at then n = tonumber(at); golden[n] = {}
    elseif n then golden[n][#golden[n] + 1] = l end
end
for i, b in pairs(golden) do golden[i] = table.concat(b, "\n") end
T:arm("1 the corpus has its cases, each with a golden block", #cases >= 60 and #golden == #cases, #cases .. " cases, " .. #golden .. " blocks")

-- The snapshot: copied until it ANSWERS, and named by its bytes. A copy taken while the file is rewritten can be
-- empty, and a shell runs an empty file with rc 0.
local PLAN = fixture.plan_binary()
if PLAN == "" then T:refuse("no-plan-binary") end
local W = T:scratch()
local SNAP = W.abs .. "/" .. PLAN:match("[^/\\]+$")
local s = T:run{ SH, "-s", "--", PLAN, SNAP, timeout_ms = 120000, stdin = [[
i=0
until cp "$1" "$2" 2>/dev/null && chmod +x "$2" && caps="$("$2" capabilities 2>/dev/null)" && [ -n "$caps" ]; do
    i=$((i + 1)); [ "$i" -lt 60 ] || exit 1
    sleep 0.3
done
{ sha256sum "$2" 2>/dev/null || shasum -a 256 "$2" 2>/dev/null; } | cut -d' ' -f1
caps=" $(printf '%s' "$caps" | tr -s '\r\n' '  ') "; case "$caps" in *" json "*) echo has-json ;; esac
exit 0
]] }
if s.code ~= 0 then T:refuse("snapshot-failed", PLAN) end
local sha = (s.stdout or ""):match("^\\?(%x+)")
out.line("note:json-get-parity:binary=" .. PLAN .. " sha256=" .. tostring(sha))
T:arm("2 the binary under test is named by its sha256, and has the json verb", sha ~= nil and #sha == 64 and text.contains(s.stdout, "has-json"), s.stdout)

-- Every case under a tool: how many match, and the report a divergence leaves.
local function judge(tool, list, want)
    local good, report = 0, {}
    for i, c in ipairs(list) do
        local got, err = answer(tool, c)
        if got == want[i] then good = good + 1
        else
            report[#report + 1] = "mismatch:" .. i .. ":" .. c.filter
            report[#report + 1] = "  want: " .. tostring(want[i]):gsub("\n", "|")
            report[#report + 1] = "  got:  " .. got:gsub("\n", "|")
            report[#report + 1] = "  stderr: " .. err:sub(1, 400):gsub("[\r\n]+", "|")
        end
    end
    return good, table.concat(report, "\n")
end
local GET = { SNAP, "json", "get" }
local good, report = judge(GET, cases, golden)
T:arm("3 every case matches the golden, stdout and exit status", good == #cases and good > 0, good .. "/" .. #cases .. "\n" .. report)
local big = { argv = { "-n", "null" }, filter = "null", input = ("0"):rep(100000) .. "1" }
good, report = judge(GET, { big }, { "null\nrc=0" })
T:arm("4 a -n case whose input outgrows the pipe is not killed by it", good == 1, report:sub(1, 300))

-- NEGATIVE CONTROL: a tool that answers junk matches nothing, and the report says why.
fs.write(W.rel .. "/junk.sh", "echo junk\necho boom-from-stub >&2\n")
local few, fewer = {}, {}
for i = 1, 5 do few[i], fewer[i] = cases[i], golden[i] end
good, report = judge({ SH, W.abs .. "/junk.sh" }, few, fewer)
T:arm("5 CONTROL a diverging tool matches nothing, and its want, got and stderr are named", good == 0 and text.contains(report, "mismatch:1:")
    and text.contains(report, "  want: {|") and text.contains(report, "  got:  junk|rc=0") and text.contains(report, "  stderr: boom-from-stub"), report:sub(1, 300))
good = judge(GET, few, { golden[2], golden[1], golden[4], golden[5], golden[3] })
T:arm("5 MUTATION answers judged against other cases' goldens fail", good < 5, good)
-- Exit status counts: the same bytes with another code are a mismatch.
good = judge(GET, { cases[1] }, { (golden[1]:gsub("rc=0$", "rc=5")) })
T:arm("5 MUTATION the right bytes with the wrong exit status fail", good == 0, good)

if JQ then
    local probe = answer({ JQ }, { argv = { "." }, input = "1" })
    local drift = 0
    for i, c in ipairs(cases) do
        local live = answer({ JQ }, c)
        if text.contains(probe, "\r") then live = live:gsub("\r\n", "\n") end -- a native Windows jq writes CRLF
        if live ~= golden[i] then
            drift = drift + 1
            out.line("drift:" .. i .. ":" .. c.filter .. " (host jq disagrees with the golden; advisory)")
        end
    end
    if drift > 0 then out.line("note:json-get-parity:drift=" .. drift) end
end

T:finish()
