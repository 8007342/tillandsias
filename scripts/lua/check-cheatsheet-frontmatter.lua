-- check-cheatsheet-frontmatter.lua — PORTED from check-cheatsheet-frontmatter.sh
-- (the shell-to-lua carried obligation, paid by 1572-nqx5). Every authored
-- cheatsheet must carry YAML frontmatter (order 782-avtk).
--
--   tillandsias-plan script run scripts/lua/check-cheatsheet-frontmatter.lua [-- --selftest]
--
-- WHY. methodology/cheatsheets.yaml -> cheatsheet_binding requires frontmatter
-- "so the validator can classify tier, authority, status, provenance, and
-- lifecycle metadata without relying on ad hoc filename heuristics" — but
-- nothing enforced it, and cheatsheets/TEMPLATE.md (the file authors copy)
-- taught a PROSE provenance section and no frontmatter at all. Following the
-- template produced a sheet the canon rejects. One such sheet was already in
-- the tree: runtime/forge-loss-on-shutdown-window.md carried HTML-comment
-- provenance, so its tier, sources and last_verified were invisible to every
-- frontmatter-parsing gate.
--
-- This matters because the experts treat cheatsheets as ground truth
-- (methodology.yaml -> cheatsheets_are_ground_truth_and_enforced_by_local_experts).
-- A sheet no gate can classify is an uncitable claim wearing the same clothes
-- as a verified one — worse than a missing sheet, because it looks covered.
--
-- SCOPE: the AUTHORED tree only (cheatsheets/). The derived copy
-- images/default/cheatsheets/ inherits frontmatter by construction and is
-- guarded for equality by scripts/stage-image-cheatsheets.sh instead — see
-- methodology/cheatsheets.yaml -> storage_and_authority.
--
-- EXEMPT: INDEX.md (generated by regenerate-cheatsheet-index.sh; it is a
-- directory listing, not a cheatsheet). TEMPLATE.md is NOT exempt — the whole
-- point is that the template must produce what the canon requires.
--
-- Output grammar (exactly one line on stdout), unchanged from the .sh:
--   ^(ok:cheatsheet-frontmatter:[0-9]+ checked|violation:missing-frontmatter:[0-9]+)$
-- The offenders and the why/remedy go to stderr.

local DIR = "cheatsheets"

-- A file HAS frontmatter iff its very first line is exactly `---`. That is the
-- YAML-document opener every parser in this repo keys on; a `---` further down
-- is a horizontal rule, not frontmatter, so the check is deliberately strict
-- about position rather than merely grepping for the token.
local function has_frontmatter(body)
    local first = body:match("^([^\n]*)") or ""
    return first:gsub("\r$", "") == "---"
end

local function basename(p) return p:match("([^/]+)$") or p end

-- judge({ {path, body}, ... }) -> checked, offenders
local function judge(files)
    local checked, offenders = 0, {}
    for _, f in ipairs(files) do
        if basename(f[1]) ~= "INDEX.md" then
            checked = checked + 1
            if not has_frontmatter(f[2]) then offenders[#offenders + 1] = f[1] end
        end
    end
    return checked, offenders
end

if arg[1] == "--selftest" then
    -- NEGATIVE CONTROL: the check must distinguish "frontmatter absent" from
    -- "file merely contains a --- somewhere". Without this a horizontal rule
    -- would satisfy the gate and the whole check would be decorative. The .sh
    -- wrote these to a mktemp dir; fs.write is confined to the repository, and
    -- the cases are about the decision, so they are judged in memory.
    local fail = 0
    local function case(desc, files, want_missing)
        local _, off = judge(files)
        if #off ~= want_missing then
            log.raw("SELFTEST-FAIL: " .. desc)
            fail = fail + 1
        end
    end
    case("valid frontmatter rejected", { { "good/sheet.md", "---\ntags: [x]\n---\n# Title\n" } }, 0)
    case("missing frontmatter accepted", { { "bad/sheet.md", "# Title\n\n<!-- provenance: prose only -->\n" } }, 1)
    case("a horizontal rule was accepted as frontmatter", { { "hr/sheet.md", "# Title\n\nsome text\n\n---\n\nmore text\n" } }, 1)
    case("INDEX.md was not exempt", { { "good/INDEX.md", "# Index\n" } }, 0)
    if fail ~= 0 then verdict.emit("violation:cheatsheet-frontmatter-selftest:" .. fail .. " failed", 1) end
    verdict.emit("ok:cheatsheet-frontmatter-selftest:4 cases", 0)
end

local ok_walk, walked = pcall(fs.walk, DIR, { suffix = ".md" })
if not ok_walk or type(walked) ~= "table" then
    log.raw("  why: the authored cheatsheet tree " .. DIR .. "/ could not be listed from the repository root")
    log.raw("  remedy: run it from a checkout that has " .. DIR .. "/ (tillandsias-plan script run resolves the root from its own location)")
    verdict.emit("blocked:cheatsheet-frontmatter:no-tree:" .. DIR, 2)
end
local files = {}
for _, p in ipairs(walked) do
    local rel = p
    if rel:sub(1, #DIR + 1) ~= DIR .. "/" then rel = DIR .. "/" .. rel end
    local okr, body = pcall(fs.read, rel)
    files[#files + 1] = { rel:sub(#DIR + 2), okr and body or "" }
end
table.sort(files, function(a, b) return a[1] < b[1] end)

local checked, offenders = judge(files)
if #offenders > 0 then
    for _, o in ipairs(offenders) do log.raw("  " .. o) end
    log.raw("  why: the first line of each file above is not `---`, so no gate can read its tier, sources or last_verified")
    log.raw("  remedy: copy the frontmatter block from cheatsheets/TEMPLATE.md to the top of each and fill it in")
    verdict.emit("violation:missing-frontmatter:" .. #offenders, 1)
end
verdict.emit("ok:cheatsheet-frontmatter:" .. checked .. " checked", 0)
