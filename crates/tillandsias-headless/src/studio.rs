//! ORDER 1860-auhm — the studio lane contract.
//!
//! Every visual web studio is declared once in `images/studio/registry.lua`
//! (Lua owns the registry; `scripts/lua/build-studio-registry.lua` writes
//! `data/studios.json`, embedded here). This module only consumes it:
//! framework detection and the choice list (`webstudio.options`, 1969-7qm7; `studio_options` is its deprecated alias), the web lane a
//! studio launches as (the OpenCode Web route, OTP and window, under
//! `studio.<label>`), and the co-edit feed (`webstudio.changes`), read from the
//! forge's own checkout.
//!
//! The write-back guard is NOT here: saves land in the forge's checkout, so the
//! guard runs where the write happens, in the studio front
//! (`images/studio/studio-front.js`).
//! @trace order:1860-auhm, spec:web-studio-lane

// The detection, choice and feed halves serve the MCP tools, which exist only
// with host-services.
#![cfg_attr(not(feature = "host-services"), allow(dead_code))]

use std::sync::OnceLock;

use serde::Deserialize;

#[derive(Debug, Deserialize)]
pub(crate) struct Registry {
    pub frameworks: Vec<Framework>,
    pub studios: Vec<Studio>,
}

#[derive(Debug, Deserialize)]
pub(crate) struct Framework {
    pub id: String,
    #[serde(default)]
    pub files_any: Vec<String>,
    #[serde(default)]
    pub package_deps_any: Vec<String>,
    #[serde(default)]
    pub package_deps_all: Vec<String>,
}

/// The fields the launcher reads; `save_adapter` and `write_allowlist` are
/// read by the studio front, from the same JSON.
#[derive(Debug, Deserialize)]
pub(crate) struct Studio {
    pub id: String,
    pub name: String,
    pub brief: String,
    /// 2026-ggu8: the content this studio is better and worse at, and what a
    /// save edits; build-studio-registry.lua refuses a studio without them.
    pub good_for: Vec<String>,
    pub not_for: Vec<String>,
    pub edits: String,
    pub license: String,
    pub frameworks: Vec<String>,
    pub entry: Vec<String>,
    pub port: u16,
    pub status: String,
    pub packet: String,
    #[serde(default)]
    pub needs_cloud_account: bool,
    /// 1921-2krx: `"sibling"` runs in its own container next to the forge;
    /// absent means `"forge"` (the studio runs in the forge).
    #[serde(default)]
    pub kind: Option<String>,
    /// A sibling's image; a forge studio's image is derived from its id.
    #[serde(default, rename = "image")]
    pub sibling_image: Option<String>,
    /// 2055-grzz: a TOOLS-ONLY sibling (port 0, no window) lists the MCP
    /// tools that drive it; empty for every windowed studio.
    #[serde(default)]
    pub tools: Vec<String>,
}

impl Studio {
    /// The studio's own image, stacked on the forge base and built on first
    /// use (never in a default prebuilt set).
    pub(crate) fn image(&self) -> String {
        self.sibling_image
            .clone()
            .unwrap_or_else(|| format!("studio-{}", self.id))
    }

    pub(crate) fn is_sibling(&self) -> bool {
        self.kind.as_deref() == Some("sibling")
    }

    /// 2055-grzz: no window to open; the agent uses [`Studio::tools`].
    pub(crate) fn is_tools_only(&self) -> bool {
        !self.tools.is_empty()
    }
}

pub(crate) fn registry() -> &'static Registry {
    static REG: OnceLock<Registry> = OnceLock::new();
    REG.get_or_init(|| {
        serde_json::from_str(include_str!("../data/studios.json"))
            .expect("data/studios.json is generated by build-studio-registry.lua and checked")
    })
}

pub(crate) fn find(id: &str) -> Option<&'static Studio> {
    registry().studios.iter().find(|s| s.id == id)
}

/// The project's framework from its tracked files and its package.json, by
/// the registry's signals in order; `None` when nothing matches.
pub(crate) fn detect_framework(
    files: &[String],
    package_json: Option<&str>,
) -> Option<&'static str> {
    let deps: Vec<String> = package_json
        .and_then(|p| serde_json::from_str::<serde_json::Value>(p).ok())
        .map(|v| {
            ["dependencies", "devDependencies"]
                .iter()
                .filter_map(|k| v[*k].as_object())
                .flat_map(|o| o.keys().cloned())
                .collect()
        })
        .unwrap_or_default();
    let has_dep = |d: &String| deps.contains(d);
    let has_file = |f: &String| files.iter().any(|x| x == f);
    registry()
        .frameworks
        .iter()
        .find(|fw| {
            (!fw.package_deps_all.is_empty() && fw.package_deps_all.iter().all(has_dep))
                || fw.package_deps_any.iter().any(has_dep)
                || fw.files_any.iter().any(has_file)
        })
        .map(|fw| fw.id.as_str())
}

/// One line of the choice list.
#[derive(Debug, serde::Serialize, PartialEq)]
pub(crate) struct StudioOption {
    pub id: String,
    pub label: String,
    pub brief: String,
    /// 2026-ggu8: what the agent chooses by when no option is [Recommended].
    pub good_for: Vec<String>,
    pub not_for: Vec<String>,
    pub edits: String,
    pub license: String,
    pub recommended: bool,
    pub available: bool,
    pub note: Option<String>,
    /// 2055-grzz: the MCP tools of a tools-only studio (empty otherwise).
    pub tools: Vec<String>,
}

/// Every studio, with at most one `[Recommended]`: the first studio listing
/// the detected framework that needs no cloud account.
pub(crate) fn options(framework: Option<&str>) -> Vec<StudioOption> {
    let recommended = framework.and_then(|fw| {
        registry()
            .studios
            .iter()
            .find(|s| !s.needs_cloud_account && s.frameworks.iter().any(|f| f == fw))
            .map(|s| s.id.as_str())
    });
    registry()
        .studios
        .iter()
        .map(|s| {
            let rec = recommended == Some(s.id.as_str());
            let note = if s.needs_cloud_account {
                Some("needs cloud account".to_string())
            } else if s.status != "ready" {
                Some(format!("lane not built yet ({})", s.packet))
            } else if s.is_tools_only() {
                Some(format!(
                    "no window to open: use the {} tools",
                    s.tools.join(" and ")
                ))
            } else {
                None
            };
            StudioOption {
                id: s.id.clone(),
                label: if rec {
                    format!("{} [Recommended]", s.name)
                } else {
                    s.name.clone()
                },
                brief: s.brief.clone(),
                good_for: s.good_for.clone(),
                not_for: s.not_for.clone(),
                edits: s.edits.clone(),
                license: s.license.clone(),
                recommended: rec,
                available: s.status == "ready" && !s.is_tools_only(),
                note,
                tools: s.tools.clone(),
            }
        })
        .collect()
}

/// What a web lane varies: the router service prefix, the port its front
/// listens on in the forge, the image the forge container runs, and the
/// entrypoint. The OpenCode Web lane is one; each studio is another.
#[derive(Debug, Clone, PartialEq)]
pub(crate) struct WebLane {
    pub service: &'static str,
    pub port: u16,
    pub image: String,
    pub entrypoint: Option<String>,
    pub label: String,
    /// The registry id ("" for OpenCode Web).
    pub id: String,
    /// 1921-2krx: the studio runs in its own container, routed to directly;
    /// no forge is started for it.
    pub sibling: bool,
}

impl WebLane {
    pub(crate) fn opencode() -> Self {
        Self {
            service: "opencode",
            port: 4096,
            image: "forge".to_string(),
            entrypoint: None,
            label: "OpenCode Web".to_string(),
            id: String::new(),
            sibling: false,
        }
    }

    /// A studio's lane, or the refusal naming why it cannot launch yet.
    pub(crate) fn studio(id: &str) -> Result<Self, String> {
        let s = find(id).ok_or_else(|| {
            let ids: Vec<&str> = registry().studios.iter().map(|s| s.id.as_str()).collect();
            format!(
                "unknown studio {id:?}; the registry offers {}",
                ids.join(", ")
            )
        })?;
        // 1865-dn5h: a studio that needs a cloud account cannot run in the
        // offline forge, so it is refused for THAT reason, not as unbuilt.
        if s.needs_cloud_account {
            return Err(format!(
                "studio {} needs a cloud account and cannot run offline in the forge ({}); \
                 choose another studio from the list",
                s.name, s.packet
            ));
        }
        if s.status != "ready" {
            return Err(format!(
                "studio {} is listed but its lane is not built yet: order {} lands its image",
                s.name, s.packet
            ));
        }
        // 2055-grzz: a tools-only studio has no window to launch, and the
        // sibling launcher would otherwise start the ComfyUI appliance for it.
        if s.is_tools_only() {
            return Err(format!(
                "studio {} has no window to open: a forge agent uses the {} MCP tools \
                 (each call runs the {} appliance with no network)",
                s.name,
                s.tools.join(" and "),
                s.image()
            ));
        }
        Ok(Self {
            service: "studio",
            port: s.port,
            image: s.image(),
            entrypoint: s.entry.first().cloned(),
            label: format!("{} studio", s.name),
            id: s.id.clone(),
            sibling: s.is_sibling(),
        })
    }

    /// The studio id this lane serves (empty for OpenCode Web).
    pub(crate) fn studio_id(&self) -> &str {
        &self.id
    }

    /// The router host for this lane: `<service>.<project label>`.
    pub(crate) fn route_host(&self, project_label: &str) -> String {
        format!("{}.{project_label}", self.service)
    }

    /// The images this lane ensures, in build order. The studio image comes
    /// last, on top of the forge it is stacked on.
    pub(crate) fn images(&self, base: &[&'static str]) -> Vec<String> {
        let mut v: Vec<String> = base.iter().map(|s| s.to_string()).collect();
        if !v.contains(&self.image) {
            v.push(self.image.clone());
        }
        v
    }
}

/// The forge's checkout of `project`.
pub(crate) fn checkout_dir(project: &str) -> String {
    format!("/home/forge/src/{project}")
}

/// The git argv (run inside the forge) for the co-edit feed since `cursor`,
/// oldest first. Without a cursor, the last 20 commits. A cursor that is not a
/// commit id is refused, so nothing in the request reaches git as an option.
pub(crate) fn changes_git_args(cursor: Option<&str>) -> Result<Vec<String>, String> {
    let mut a: Vec<String> = [
        "log",
        "--reverse",
        "--no-color",
        "--format=%x1e%H%x1f%an%x1f%s",
        "-p",
    ]
    .iter()
    .map(|s| s.to_string())
    .collect();
    match cursor {
        Some(c) => {
            if !(7..=40).contains(&c.len()) || !c.chars().all(|ch| ch.is_ascii_hexdigit()) {
                return Err(format!("cursor must be a commit id, got {c:?}"));
            }
            a.push(format!("{c}..HEAD"));
        }
        None => a.push("-n20".to_string()),
    }
    Ok(a)
}

/// One commit in the feed.
#[derive(Debug, serde::Serialize, PartialEq)]
pub(crate) struct Change {
    pub sha: String,
    pub author: String,
    pub subject: String,
    pub paths: Vec<String>,
    pub diff: String,
}

/// Each commit's diff is capped, so one large save cannot flood the agent.
const DIFF_CAP: usize = 16 * 1024;

pub(crate) fn parse_changes(stdout: &str) -> Vec<Change> {
    stdout
        .split('\u{1e}')
        .filter(|r| !r.trim().is_empty())
        .filter_map(|rec| {
            let (head, diff) = rec.split_once('\n').unwrap_or((rec, ""));
            let mut f = head.split('\u{1f}');
            let (sha, author, subject) = (f.next()?, f.next()?, f.next()?);
            let mut paths: Vec<String> = diff
                .lines()
                .filter_map(|l| l.strip_prefix("diff --git a/"))
                .filter_map(|l| l.split_once(" b/").map(|(_, b)| b.to_string()))
                .collect();
            paths.dedup();
            let diff = diff.trim_matches('\n');
            let diff: String = if diff.len() > DIFF_CAP {
                let mut end = DIFF_CAP;
                while !diff.is_char_boundary(end) {
                    end -= 1;
                }
                format!("{}\n… (diff truncated)", &diff[..end])
            } else {
                diff.to_string()
            };
            Some(Change {
                sha: sha.to_string(),
                author: author.to_string(),
                subject: subject.to_string(),
                paths,
                diff,
            })
        })
        .collect()
}

