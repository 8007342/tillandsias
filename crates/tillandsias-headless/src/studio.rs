#[cfg(feature = "host-services")]
/// `git <args>` in the lane's live forge checkout. The forge is the one
/// `local_web_preview` proves belongs to this lane; nothing in the request
/// names a container or a path.
fn git_in_lane(project: &str, instance: &str, args: &[String]) -> Result<String, String> {
    let lane = crate::local_web_preview::resolve_live_source(project, instance)?;
    let dir = checkout_dir(project);
    let mut cmd = tillandsias_podman::podman_cmd_sync();
    cmd.args(["exec", &lane.forge_id, "git", "-C", &dir])
        .args(args);
    let out = cmd
        .output_bounded(std::time::Duration::from_secs(15))
        .map_err(|e| format!("studio: git in the forge failed: {e}"))?;
    if !out.status.success() {
        return Err(format!(
            "studio: git {} exited {}: {}",
            args.first().map(String::as_str).unwrap_or(""),
            out.status,
            String::from_utf8_lossy(&out.stderr).trim()
        ));
    }
    Ok(String::from_utf8_lossy(&out.stdout).into_owned())
}

