    /// A user save and then an agent edit to the same file are two commits,
    /// in order, each with its path and diff (the co-edit scenario), read by
    /// the same argv the MCP tool runs in the forge.
    #[test]
    fn the_feed_returns_each_saved_path_with_its_diff_in_commit_order() {
        let dir = std::env::temp_dir().join(format!("studio-feed-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        let git = |args: &[&str], who: &str| {
            let out = std::process::Command::new("git")
                .current_dir(&dir)
                .args([
                    "-c",
                    &format!("user.name={who}"),
                    "-c",
                    "user.email=t@example.invalid",
                ])
                .args(args)
                .env("GIT_CONFIG_GLOBAL", "/dev/null")
                .env("GIT_CONFIG_NOSYSTEM", "1")
                .output()
                .unwrap();
            assert!(
                out.status.success(),
                "{args:?}: {}",
                String::from_utf8_lossy(&out.stderr)
            );
            String::from_utf8(out.stdout).unwrap()
        };
        git(&["init", "-q", "-b", "main"], "t");
        std::fs::write(dir.join("index.html"), "<h1>a</h1>\n").unwrap();
        git(&["add", "."], "t");
        git(&["commit", "-q", "-m", "init"], "t");
        let cursor = git(&["rev-parse", "HEAD"], "t").trim().to_string();
        std::fs::write(dir.join("index.html"), "<h1>b</h1>\n").unwrap();
        git(
            &["commit", "-qam", "studio(grapesjs): save index.html"],
            "user",
        );
        std::fs::write(dir.join("index.html"), "<h1>c</h1>\n").unwrap();
        git(&["commit", "-qam", "agent: tighten heading"], "agent");

        let args = changes_git_args(Some(&cursor)).unwrap();
        let argv: Vec<&str> = args.iter().map(String::as_str).collect();
        let feed = parse_changes(&git(&argv, "t"));
        let _ = std::fs::remove_dir_all(&dir);

        assert_eq!(feed.len(), 2, "{feed:?}");
        assert_eq!(feed[0].subject, "studio(grapesjs): save index.html");
        assert_eq!(feed[0].author, "user");
        assert_eq!(feed[0].paths, ["index.html"]);
        assert!(feed[0].diff.contains("+<h1>b</h1>"), "{}", feed[0].diff);
        assert_eq!(feed[1].author, "agent");
        assert!(feed[1].diff.contains("+<h1>c</h1>"));
        assert_ne!(feed[0].sha, feed[1].sha);
    }
